export function cs2Translator(lang) {
  const column = lang === "ru" ? 0 : lang === "en" ? 1 : -1;
  return (message, ...values) => {
    const text = column >= 0 && Object.hasOwn(CS2_TEXT, message) ? CS2_TEXT[message][column] : message;
    return values.length ? text.replace(/\{(\d+)\}/g, (_, i) => String(values[i])) : text;
  };
}
