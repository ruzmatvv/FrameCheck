// bt("ru", "welcome", "Ali") -> the text with {0} filled. Values are inserted as they are: escape them first (botEscape).
export function bt(lang, key, ...values) {
  const table = TEXT[lang] || TEXT.uz;
  const value = table[key] ?? TEXT.uz[key];
  if (typeof value !== "string") return value ?? key;
  return value.replace(/\{(\d+)\}/g, (_, i) => String(values[i] ?? ""));
}
